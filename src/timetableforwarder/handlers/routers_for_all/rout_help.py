        "🎓 <b>Справка по боту расписания</b>\n\n"
        "<b>Что делает бот:</b>\n"
        "• Автоматически распознаёт текст расписания с картинок из канала колледжа\n"
        "• Пересылает расписание в выбранные группы студентов\n"
        "• Уведомляет о изменениях в расписании\n\n"
        "<b>Как настроить:</b>\n"
        "1. Нажмите /start для начала работы\n"
        "2. Выберите кнопку 'Настроить рассылку'\n"
        "3. Выберите свою группу из списка\n"
        "4. Готово! Вы будете получать расписание для своей группы\n\n"
        "<b>Доступные команды:</b>\n"
        "• /start - начать работу с ботом\n"
        "• /help - показать эту справку\n\n"
        "Если у вас есть вопросы, обратитесь к создателю @kolo_id\n\n"
